   byte[] pktBuffer = null;
   int pktLen = 0;

   public static int getTypeOfPacket(byte[] RxBuffer) {
      return RxBuffer[0] & 7;
   }

   public byte[] createPacket(int typeOfPacket, byte[] dataBuffer, int txDataLength) {
      byte[] buff = new byte[5 + txDataLength];
      int ulPacketLengthWithoutCRC = txDataLength + 3;
      buff[0] = (byte)typeOfPacket;
      buff[1] = (byte)((txDataLength & 0xFF00) >> 8);
      buff[2] = (byte)(txDataLength & 0xFF);

      for (int i = 0; i < txDataLength; i++) {
         buff[i + 3] = dataBuffer[i];
      }

      int CRC16 = calculateCRC(buff, ulPacketLengthWithoutCRC);
      buff[ulPacketLengthWithoutCRC] = (byte)((CRC16 & 0xFF00) >> 8);
      buff[ulPacketLengthWithoutCRC + 1] = (byte)(CRC16 & 0xFF);
      this.pktBuffer = buff;
      this.pktLen = ulPacketLengthWithoutCRC + 2;
      return this.pktBuffer;
   }

   public static boolean checkHeader(byte[] RxBuffer) {
      if ((RxBuffer[0] & 240) != 0) {
         return false;
      } else if ((RxBuffer[0] & 8) != 8) {
         return false;
      } else {
         switch (RxBuffer[0] & 7) {
            case 0:
            case 1:
            case 5:
            case 6:
               return true;
            case 2:
            case 3:
            case 4:
            default:
               return false;
         }
      }
   }

   public static int calculateCRC(byte[] pcData, int uiLength) {
      int auxpcdata = 0;
      int usInitialCrc = 65535;
      int ucCrc16Low = usInitialCrc & 0xFF;
      int ucCrc16High = usInitialCrc >> 8;

      for (int uiCrcIndex = 0; uiCrcIndex < uiLength; uiCrcIndex++) {
         int ucCrc16Aux1 = crcHighArray[ucCrc16High];
         int ucCrc16Aux2 = crcLowArray[ucCrc16High];
         ucCrc16High = ucCrc16Aux1 ^ ucCrc16Low;
         auxpcdata = pcData[uiCrcIndex] & 255;
         ucCrc16Low = ucCrc16Aux2 ^ auxpcdata;
      }

      return ucCrc16High * 256 + ucCrc16Low ^ usInitialCrc;
   }

   public static boolean checkCRC(byte[] buff) {
      int ulRxDataLength = getDataLength(buff);
      int ulPacketLengthWithoutCRC = ulRxDataLength + 3;
      int CRC16 = calculateCRC(buff, ulPacketLengthWithoutCRC);
      int CRC16Received = (buff[ulPacketLengthWithoutCRC] & 255) << 8;
      CRC16Received ^= buff[ulPacketLengthWithoutCRC + 1] & 255;
      return CRC16 == CRC16Received;
   }

   public static int getDataLength(byte[] packet) {
      int rtn = packet[1] & 255;
      return (rtn << 8) + (packet[2] & 0xFF);
   }

   public static byte[] getData(byte[] packet) {
      int datalen = getDataLength(packet);
      byte[] data = new byte[datalen];
      System.arraycopy(packet, 3, data, 0, datalen);
      return data;
   }
